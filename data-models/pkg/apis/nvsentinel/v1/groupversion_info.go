package v1

import (
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
)

const (
	// GroupName is the API group of ExternalRemediationRequest and
	// MaintenanceRequest. It is distinct from the janitor.dgxc.nvidia.com group
	// used by RebootNode/GPUReset/TerminateNode.
	GroupName = "nvsentinel.dgxc.nvidia.com"

	// Version is the API version of ExternalRemediationRequest and
	// MaintenanceRequest.
	//
	// The version is "v1" to match the CRDs generated by protoc-gen-crd, which
	// hardcodes "v1" in its plugin source (see plugin.go in
	// github.com/yandex/protoc-gen-crd) and does not currently expose a way to
	// configure the version per CRD. The HealthEventResource CRD generated by
	// the same plugin uses the same v1 convention. Despite the v1 version
	// string, both APIs are still pre-stable: ADR-040 governs the lifecycle of
	// ExternalRemediationRequest, and ADR-051 governs the lifecycle of
	// MaintenanceRequest.
	Version = "v1"

	// ExternalRemediationRequestKind is the kind of ExternalRemediationRequest.
	ExternalRemediationRequestKind = "ExternalRemediationRequest"

	// ExternalRemediationRequestResource is the plural resource name of
	// ExternalRemediationRequest.
	ExternalRemediationRequestResource = "externalremediationrequests"

	// MaintenanceRequestKind is the kind of MaintenanceRequest.
	MaintenanceRequestKind = "MaintenanceRequest"

	// MaintenanceRequestResource is the plural resource name of
	// MaintenanceRequest.
	MaintenanceRequestResource = "maintenancerequests"
)

var (
	// GroupVersion is the GroupVersion of ExternalRemediationRequest and
	// MaintenanceRequest.
	GroupVersion = schema.GroupVersion{Group: GroupName, Version: Version}

	// SchemeBuilder is the SchemeBuilder for the nvsentinel.dgxc.nvidia.com
	// API group. It is independent of the SchemeBuilders of the other
	// NVSentinel API groups, so each group can be registered independently.
	SchemeBuilder = runtime.NewSchemeBuilder(addKnownTypes)

	// AddToScheme adds ExternalRemediationRequest, MaintenanceRequest and
	// their list types to the given scheme.
	AddToScheme = SchemeBuilder.AddToScheme
)

func addKnownTypes(scheme *runtime.Scheme) error {
	scheme.AddKnownTypes(
		GroupVersion,
		&ExternalRemediationRequest{},
		&ExternalRemediationRequestList{},
		&MaintenanceRequest{},
		&MaintenanceRequestList{},
	)
	metav1.AddToGroupVersion(scheme, GroupVersion)

	return nil
}
