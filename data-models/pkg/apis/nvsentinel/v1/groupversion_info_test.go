package v1

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
)

func TestGroupVersion_MatchesCRDs_IsNVSentinelV1(t *testing.T) {
	t.Parallel()

	// The CRDs generated by protoc-gen-crd serve both kinds at this apiVersion.
	assert.Equal(t, "nvsentinel.dgxc.nvidia.com/v1", GroupVersion.String())
}

func TestAddToScheme_AllKinds_RegisteredUnderGroupVersion(t *testing.T) {
	t.Parallel()

	scheme := runtime.NewScheme()
	require.NoError(t, AddToScheme(scheme))

	cases := []struct {
		kind     string
		expected runtime.Object
	}{
		{kind: ExternalRemediationRequestKind, expected: &ExternalRemediationRequest{}},
		{kind: "ExternalRemediationRequestList", expected: &ExternalRemediationRequestList{}},
		{kind: MaintenanceRequestKind, expected: &MaintenanceRequest{}},
		{kind: "MaintenanceRequestList", expected: &MaintenanceRequestList{}},
	}

	for _, tc := range cases {
		t.Run(tc.kind, func(t *testing.T) {
			t.Parallel()

			gvk := GroupVersion.WithKind(tc.kind)

			obj, err := scheme.New(gvk)
			require.NoError(t, err)
			assert.IsType(t, tc.expected, obj)

			gvks, unversioned, err := scheme.ObjectKinds(tc.expected)
			require.NoError(t, err)
			assert.False(t, unversioned)
			assert.Equal(t, []schema.GroupVersionKind{gvk}, gvks)
		})
	}
}
