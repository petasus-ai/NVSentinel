package v1

import (
	"bytes"
	"encoding/json"
	"fmt"

	"google.golang.org/protobuf/encoding/protojson"
	"google.golang.org/protobuf/proto"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// The ExternalRemediationRequest and MaintenanceRequest wrappers embed
// proto-generated types in their Spec and Status fields. Several of those types
// use google.protobuf well-known types — most prominently
// google.protobuf.Timestamp on Condition — that have a canonical JSON encoding
// defined by the protobuf JSON spec (RFC3339 strings for Timestamp) and emitted
// by google.golang.org/protobuf/encoding/protojson.
//
// The CRD schema generated by protoc-gen-crd matches that canonical encoding
// (lastTransitionTime: type=string, format=RFC3339). However, the standard
// encoding/json package — which controller-runtime's client and the
// Kubernetes apimachinery serializer ultimately invoke — does NOT know about
// proto well-known types and falls back to reflecting over the Go struct,
// producing `{"seconds": N, "nanos": M}` for Timestamp. That object form
// fails CRD validation with HTTP 422.
//
// The fix is to override MarshalJSON/UnmarshalJSON on the wrappers so that
// TypeMeta and ObjectMeta flow through encoding/json as usual, but Spec and
// Status are routed through protojson. This keeps proto as the source of
// truth for the schema (per ADR-040 and ADR-051) without introducing a
// separate hand-mirrored Go shape.
//
// Future spec fields that use other well-known proto types
// (google.protobuf.Duration, etc.) get the correct behavior for free since
// protojson handles them all canonically.
//
// Both wrappers share the generic helpers below; each type only supplies its
// kind name (for error messages) and its fields.

// protojsonUnmarshalOpts is the lenient unmarshal config used for k8s-side
// reads. DiscardUnknown=true matches apimachinery's behavior of tolerating
// server-side schema additions; everything else is the protojson default.
var protojsonUnmarshalOpts = protojson.UnmarshalOptions{DiscardUnknown: true}

// objectEnvelope mirrors the wire shape of a wrapper but pre-encodes Spec and
// Status as opaque JSON blobs so they can be produced by protojson (marshal)
// or fed to protojson (unmarshal). TypeMeta and ObjectMeta are standard k8s
// types handled by encoding/json.
type objectEnvelope struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`
	Spec              json.RawMessage `json:"spec,omitempty"`
	Status            json.RawMessage `json:"status,omitempty"`
}

// listEnvelope mirrors the wire shape of a list wrapper. encoding/json
// delegates each item to the item type's MarshalJSON / UnmarshalJSON, which
// in turn applies protojson to Spec / Status.
type listEnvelope[T any] struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []T `json:"items"`
}

// message is a pointer to a generated protobuf message. The constraint lets
// the helpers allocate a new message with new(T), compare the pointer with
// nil, and pass it to protojson.
type message[T any] interface {
	*T
	proto.Message
}

// marshalObject encodes TypeMeta and ObjectMeta with encoding/json and a
// non-nil spec / status with protojson. A nil spec or status is omitted. This
// ensures proto well-known types (Timestamp, etc.) emit their canonical JSON
// forms rather than the {seconds, nanos} reflection-default form, matching the
// CRD's OpenAPI schema.
func marshalObject[S, T any, PS message[S], PT message[T]](
	kind string, typeMeta metav1.TypeMeta, objectMeta metav1.ObjectMeta, spec PS, status PT,
) ([]byte, error) {
	out := objectEnvelope{TypeMeta: typeMeta, ObjectMeta: objectMeta}

	if spec != nil {
		b, err := protojson.Marshal(spec)
		if err != nil {
			return nil, fmt.Errorf("marshal %s.spec via protojson: %w", kind, err)
		}

		out.Spec = b
	}

	if status != nil {
		b, err := protojson.Marshal(status)
		if err != nil {
			return nil, fmt.Errorf("marshal %s.status via protojson: %w", kind, err)
		}

		out.Status = b
	}

	return json.Marshal(&out)
}

// unmarshalObject is the inverse of marshalObject: TypeMeta and ObjectMeta via
// encoding/json, spec / status via protojson with DiscardUnknown enabled so
// that forward-compat field additions on the server side don't break older
// clients. A missing or null spec / status becomes nil.
//
// The outputs are pointers to the receiver's fields so that the assignment
// order and the partial result on error stay exactly as in a hand-written
// UnmarshalJSON: an envelope error leaves the receiver untouched; otherwise
// TypeMeta and ObjectMeta are assigned first, then spec, then status, and a
// protojson error leaves that field and the fields after it untouched.
func unmarshalObject[S, T any, PS message[S], PT message[T]](
	kind string, data []byte,
	typeMeta *metav1.TypeMeta, objectMeta *metav1.ObjectMeta, spec *PS, status *PT,
) error {
	var in objectEnvelope
	if err := json.Unmarshal(data, &in); err != nil {
		return fmt.Errorf("unmarshal %s envelope: %w", kind, err)
	}

	*typeMeta = in.TypeMeta
	*objectMeta = in.ObjectMeta

	if isJSONPresent(in.Spec) {
		m := PS(new(S))
		if err := protojsonUnmarshalOpts.Unmarshal(in.Spec, m); err != nil {
			return fmt.Errorf("unmarshal %s.spec via protojson: %w", kind, err)
		}

		*spec = m
	} else {
		*spec = nil
	}

	if isJSONPresent(in.Status) {
		m := PT(new(T))
		if err := protojsonUnmarshalOpts.Unmarshal(in.Status, m); err != nil {
			return fmt.Errorf("unmarshal %s.status via protojson: %w", kind, err)
		}

		*status = m
	} else {
		*status = nil
	}

	return nil
}

// marshalList encodes a list wrapper. ListMeta uses encoding/json as it is a
// standard k8s type; each item goes through its own MarshalJSON.
func marshalList[T any](typeMeta metav1.TypeMeta, listMeta metav1.ListMeta, items []T) ([]byte, error) {
	return json.Marshal(&listEnvelope[T]{TypeMeta: typeMeta, ListMeta: listMeta, Items: items})
}

// unmarshalList decodes a list wrapper; each item goes through its own
// UnmarshalJSON. An error leaves the receiver untouched.
func unmarshalList[T any](
	kind string, data []byte, typeMeta *metav1.TypeMeta, listMeta *metav1.ListMeta, items *[]T,
) error {
	var in listEnvelope[T]
	if err := json.Unmarshal(data, &in); err != nil {
		return fmt.Errorf("unmarshal %s: %w", kind, err)
	}

	*typeMeta = in.TypeMeta
	*listMeta = in.ListMeta
	*items = in.Items

	return nil
}

// isJSONPresent reports whether the given RawMessage carries a real JSON
// payload, treating empty, missing, or explicit `null` as absence.
func isJSONPresent(raw json.RawMessage) bool {
	if len(raw) == 0 {
		return false
	}

	return !bytes.Equal(bytes.TrimSpace(raw), []byte("null"))
}

// MarshalJSON serialises an ExternalRemediationRequest with TypeMeta and
// ObjectMeta via encoding/json and Spec / Status via protojson.
func (e *ExternalRemediationRequest) MarshalJSON() ([]byte, error) {
	return marshalObject(ExternalRemediationRequestKind, e.TypeMeta, e.ObjectMeta, e.Spec, e.Status)
}

// UnmarshalJSON deserialises an ExternalRemediationRequest with the inverse of
// MarshalJSON.
func (e *ExternalRemediationRequest) UnmarshalJSON(data []byte) error {
	return unmarshalObject(ExternalRemediationRequestKind, data, &e.TypeMeta, &e.ObjectMeta, &e.Spec, &e.Status)
}

// MarshalJSON delegates each item to ExternalRemediationRequest.MarshalJSON.
func (l *ExternalRemediationRequestList) MarshalJSON() ([]byte, error) {
	return marshalList(l.TypeMeta, l.ListMeta, l.Items)
}

// UnmarshalJSON deserialises the envelope and delegates each item to
// ExternalRemediationRequest.UnmarshalJSON.
func (l *ExternalRemediationRequestList) UnmarshalJSON(data []byte) error {
	return unmarshalList(ExternalRemediationRequestKind+"List", data, &l.TypeMeta, &l.ListMeta, &l.Items)
}

